"""学期是拿来分组和排序的，所以它得是一个值，不是一段自由文本。

线上已经出现过 `2025-2026第二学期` 和 `2025-2026 第二学期` 两条记录指同一个学期
（task 1 和 task 2，同一位老师隔了几天填的）。它们在任何"按学期归组"的视图里都会
各占一格，回流到工作台之后更是分辨不出谁是谁。

归一化放在这里、由建任务的路由调用，而不是只做成表单上的下拉：绕过界面直接调 API
的路径同样要收口，否则前端修好了、数据照样能脏。

规范形式 `YYYY-YYYY 第X学期` 的**字典序天然就是时间序**——学年是数字，
`一` U+4E00 < `二` U+4E8C——所以下游排序、分组都不需要额外的映射表。
"""

import re


# 学年之间的连接符见过半角短横、全角横线和斜杠；"学年"两个字有人写有人不写；
# 学期序号有人写汉字有人写数字（含全角）。这些都指同一件事，认下来即可。
_TERM = re.compile(
    r"^\s*(\d{4})\s*[-–—－/~至]\s*(\d{4})\s*(?:学年)?\s*第\s*([一二12１２])\s*学期\s*$"
)

_HALVES = {"一": "一", "1": "一", "１": "一", "二": "二", "2": "二", "２": "二"}


def normalize_term(value: str) -> str:
    """把老师填的学期收敛成 `YYYY-YYYY 第X学期`。

    **认不出来的原样留着，不猜。** 学期会印进课程实施大纲和教案的抬头，
    也会跟着回流进工作台的台账；把 `2025-2027 第二学期` 这种明显笔误
    自作主张改成某一年，比留着它更糟——留着至少看得出是错的。
    """
    text = (value or "").strip()
    match = _TERM.match(text)
    if match is None:
        return text

    start, end, half = match.groups()
    # 学年必须首尾相接。`2025-2027` 是笔误，不是某种写法，交给人去改。
    if int(end) != int(start) + 1:
        return text

    return f"{start}-{end} 第{_HALVES[half]}学期"
